                    <h2>About Revised National TB Control Programme</h2>

                    <p>The Revised National Tuberculosis Control Programme (RNTCP) was India's flagship, internationally recommended TB control initiative. Launched nationally in 1997, it used the DOTS (Directly Observed Treatment, Short-course) strategy to successfully diagnose and treat millions. To reflect the goal of wiping out the disease, the program was renamed to the National TB Elimination Program (NTEP).</p>

                    <p>The first technical &amp; operational guidelines for Revised National TB Control Programme (RNTCP) were developed during the initial years of implementation of the programme. The current available documents outline the guidelines on TB care in line with RNTCP National Strategic Plan for Tuberculosis Control. These guidelines were conceived by programme managers working at the national, state and district levels. Experts from national institutes, national and intermediate reference laboratories, medical colleges and partners were involved in the process of preparing it.</p>

                    <p>Standards for TB Care in India, National Strategic Plan document, Recommendations of the Joint Monitoring Mission 2012 and policy decisions taken in the National Committee on Diagnosis and Management of Tuberculosis under RNTCP, National Technical Working Group on TB-HIV, National Technical Working Group on Pediatric TB, Expert committee on regulation of newer anti-TB drugs were used as a foundation for developing these document.</p>

                    <p>Existing technical and operational guidelines, training module for medical officers, National PMDT guidelines, National Air borne infection control guidelines, Revised pediatric TB guidelines, National guidelines on partnerships, Guidelines for Quality Assurance of smear microscopy for diagnosing tuberculosis, National Framework for Joint HIV/TB Collaborative Activities and Guidelines for use of Bedaquilline in RNTCP through conditional access under programmatic management of drug resistant TB in India have also been referred.</p>

                    <p>The document covers strategies and guidelines for diagnosis and treatment of all forms of TB including pulmonary, extra-pulmonary, drug resistant TB, TB with comorbidities, pediatric TB, etc. Programme management aspects covering patient support systems, human resource management, partnerships for TB control, advocacy, communication and social mobilization, infection control measures, planning and finance are also incorporated.</p>

                    <p>These technical and operational guidelines are intended to be used by all the personnel engaged in control of TB in the country. This is a living document open to further improvements and will be updated as lessons are learned through its use in the field.</p>
